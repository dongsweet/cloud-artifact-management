import assert from 'node:assert/strict';
import test from 'node:test';
import { agentPage } from '../src/web.js';

test('Agent identity page makes trust direction and Core-owned rotation policy explicit', () => {
  const html = agentPage();
  assert.match(html, /path\.startsWith\('\/api\/v1'\)\?path\.slice\(7\):path/);
  assert.match(html, /const error=\$\('#login-error'\);error\.classList\.add\('d-none'\);try\{/);
  assert.match(html, /用户名或密码错误/);
  assert.match(html, /无法连接认证服务，请稍后重试/);
  assert.match(html, /Agent 身份公钥/);
  assert.match(html, /Core 服务公钥/);
  assert.match(html, /Agent 接入与 Core 身份/);
  assert.match(html, /cam-agent-identity-panel/);
  assert.match(html, /轮换周期和旧密钥过渡期由 Core 下发/);
  assert.match(html, /测试配对并同步状态/);
  assert.match(html, /id="password-title" class="card-title">修改初始密码/);
  assert.match(html, /id="password-help" class="alert alert-info">首次登录必须修改初始密码/);
  assert.match(html, /id="password-cancel"[^>]*>取消/);
  assert.match(html, /function showPasswordChange\(forced\)/);
  assert.match(html, /showPasswordChange\(true\)/);
  assert.match(html, /showPasswordChange\(false\)/);
  assert.match(html, /password-cancel.*?show\('app'\)/s);
  assert.match(html, /本机 Agent 身份<\/h4><div class="d-flex align-items-center gap-2">.*?id="identity-copy"/s);
  assert.match(html, /Core 服务身份<\/h4><div class="d-flex align-items-center gap-2 flex-wrap justify-content-end">.*?id="core-key-replace".*?重新配对.*?id="core-config-save".*?保存 Core 身份.*?id="core-key-cancel".*?取消/s);
  assert.doesNotMatch(html, /id="core-copy"/);
  assert.doesNotMatch(html, /id="core-config-summary"|const states=\{NOT_TESTED/);
  assert.match(html, /id="core-url" class="form-control bg-body-secondary"[^>]*readonly/);
  assert.match(html, /id="core-public-key" class="form-control agent-identity-key bg-body-secondary"[^>]*readonly/);
  assert.match(html, /id="core-fingerprint" class="form-text font-monospace text-break mt-2"/);
  assert.doesNotMatch(html, /id="core-trusted-key"|id="core-trusted-public-key"/);
  assert.doesNotMatch(html, /填写本节点可访问的 Core 基地址/);
  assert.match(html, /<div class="card-footer d-flex flex-wrap justify-content-end gap-2"><button id="core-config-test"/);
  assert.match(html, /function coreButtons\(\).*?\$\('#core-config-save'\)\.classList\.toggle\('d-none',!editingCore\)/s);
  assert.ok(html.includes("editingCore=!item.configured"));
  assert.ok(html.includes("$('#core-key-replace').classList.toggle('d-none',!item.configured||editingCore)"));
  assert.ok(html.includes("$('#core-key-replace').onclick=()=>{editingCore=true"));
  assert.ok(html.includes("$('#core-url').classList.remove('bg-body-secondary')"));
  assert.ok(html.includes("$('#core-public-key').classList.remove('bg-body-secondary')"));
  assert.ok(html.includes("$('#core-key-cancel').onclick=()=>{renderCoreConfig(coreConfig)"));
  assert.doesNotMatch(html, /立即轮换/);
  assert.match(html, /部署交付/);
  assert.match(html, /CamAgentDeliveryOpen/);
  assert.match(html, /下载明细/);
  assert.match(html, /下载人/);
  assert.match(html, /data-agent-permission="userAdmin"[\s\S]*?用户与角色/);
  assert.match(html, /id="new-agent-user"[^>]*>.*?新增账号/s);
  assert.match(html, /id="page-users"/);
  assert.match(html, /id="page-audit"/);
  assert.match(html, /data-page="audit" data-agent-permission="auditRead"/);
  assert.match(html, /mountAuditEvents/);
  assert.match(html, /data-audit-filter/);
  assert.match(html, /本地账号首次登录须修改密码/);
  assert.match(html, /data-agent-permission="configRead"/);
  assert.match(html, /data-agent-permission="businessRead"/);
  assert.match(html, /function agentCan\(permission\)/);
  assert.match(html, /const required=\{identity:'configRead','aaa-config':'configRead',artifacts:'businessRead',tasks:'businessRead',delivery:'deliveryRead',users:'userAdmin',audit:'auditRead'\}/);
  assert.match(html, /async function agentLoadUsers\(\) \{\s*if \(!agentCan\('userAdmin'\)\) return;/);
  assert.doesNotMatch(html, /agentIsSecurityAdmin/);
  assert.match(html, /data-page="aaa-config" data-agent-permission="configRead"/);
  assert.match(html, /mountAaaConfig/);
  assert.match(html, /agentCan\('businessWrite'\)\?async\(item\)/);
  assert.doesNotMatch(html, /window\.alert\s*\(|window\.confirm\s*\(|\balert\s*\(|\bconfirm\s*\(/);
});
